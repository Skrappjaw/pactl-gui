#!/bin/bash
# Build pulsar_<version>_all.deb from a clean staging tree.
#
#   ./packaging/debian/build.sh
#
# Produces:  build/pulsar_0.1.0_all.deb
#
# No debhelper required: we assemble DEBIAN/ ourselves and call
#   dpkg-deb --build --root-owner-group
# (fakeroot-free, so it works in minimal containers). Every control field
# is kept on ONE line -- dpkg-deb rejects wrapped field values.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"

PKG="pulsar"
VERSION="$(awk -F'"' '/^version[[:space:]]*=/ {print $2; exit}' "$REPO/pyproject.toml")"
ARCH="all"
DEB="${PKG}_${VERSION}_${ARCH}.deb"

STAGE="$REPO/build/deb/${PKG}_${VERSION}_${ARCH}"
OUTDIR="$REPO/build/deb"

echo "==> Pulsar $VERSION :: staging in $STAGE"
rm -rf "$STAGE"
mkdir -p "$STAGE/DEBIAN"

# ---------------------------------------------------------------- payload
# Application code (read-only, under /usr/share/pulsar) -- mirrors the
# wheel layout: a top-level 'src' package plus builtin_profiles.json
# inside src/utils/presets.
APP="$STAGE/usr/share/pulsar"
mkdir -p "$APP"
tar -C "$REPO" -cf - \
    --exclude='__pycache__' \
    --exclude='*.pyc' \
    --exclude='*.egg-info' \
    --exclude='src/*.pyc' \
    src | tar -C "$APP" -xf -
test -f "$APP/src/main.py"
test -f "$APP/src/utils/presets/builtin_profiles.json"

# /usr/bin/pulsar launcher. The repo-root 'pulsar' script cds relative to
# itself, which works for the repo-root launcher but not for a symlinked
# /usr/bin entry, so ship a small absolute-path wrapper instead.
mkdir -p "$STAGE/usr/bin"
cat > "$STAGE/usr/bin/pulsar" <<'LAUNCHER'
#!/bin/sh
# Pulsar launcher (generated by packaging/debian/build.sh)
exec /usr/bin/python3 /usr/share/pulsar/src/main.py "$@"
LAUNCHER
chmod 0755 "$STAGE/usr/bin/pulsar"

# Desktop entry: take the repo template and substitute the REAL Exec path.
mkdir -p "$STAGE/usr/share/applications"
sed 's|^Exec=PLACEHOLDER_EXEC_PATH$|Exec=/usr/bin/pulsar|' \
    "$REPO/pulsar.desktop" > "$STAGE/usr/share/applications/pulsar.desktop"
chmod 0644 "$STAGE/usr/share/applications/pulsar.desktop"
if grep -q PLACEHOLDER_EXEC_PATH "$STAGE/usr/share/applications/pulsar.desktop"; then
    echo "FATAL: PLACEHOLDER_EXEC_PATH survived substitution" >&2
    exit 1
fi

# Docs.
mkdir -p "$STAGE/usr/share/doc/pulsar"
cp "$REPO/LICENSE"  "$STAGE/usr/share/doc/pulsar/copyright"
cp "$REPO/README.md" "$STAGE/usr/share/doc/pulsar/README.md"
cp "$HERE/README.md"  "$STAGE/usr/share/doc/pulsar/packaging-debian.md"
chmod 0644 "$STAGE/usr/share/doc/pulsar/"*

# ---------------------------------------------------------------- control
# Take only the binary-package stanza out of control (skip the Source
# stanza) so every field lands on a single line.
sed -n '/^Package: /,$p' "$HERE/control" > "$STAGE/DEBIAN/control"
# dpkg requires a final newline (the multiline Description must terminate).
if [ -n "$(tail -c 1 "$STAGE/DEBIAN/control")" ]; then printf '\n' >> "$STAGE/DEBIAN/control"; fi

# No conffiles: the package ships zero /etc files, and all user data lives
# outside /usr. Debian Policy 6.5: a package with no conffiles need not
# ship the file, and an empty/invalid one would only be misleading.

install -m 0755 "$HERE/postinst" "$STAGE/DEBIAN/postinst"
install -m 0755 "$HERE/postrm"   "$STAGE/DEBIAN/postrm"

# Deterministic-ish build: no timestamps from the build host.
find "$STAGE" -exec touch -h -d '@0' {} + 2>/dev/null || true
chown -R 0:0 "$STAGE" 2>/dev/null || true

# Sanity: reject any control field accidentally wrapped onto a second line.
python3 - "$STAGE/DEBIAN/control" <<'PY'
import sys
required = ("Package:", "Version:", "Architecture:", "Maintainer:",
            "Section:", "Priority:", "Description:", "Depends:")
lines = open(sys.argv[1]).read().splitlines()
fields = [l for l in lines if l and not l.startswith(" ")]
missing = [f for f in required
           if not any(l.startswith(f) and len(l.split(":", 1)[1].strip()) > 0
                      for l in fields)]
if missing:
    sys.exit("control is missing/empty: " + ", ".join(missing))
# a wrapped Depends (the classic mistake) shows up as a bare continuation
for l in fields:
    if l.startswith("Depends:") and len(l) < 12:
        sys.exit("empty Depends")
print("control OK:", len(fields), "single-line fields")
PY

echo "==> Building $DEB"
mkdir -p "$OUTDIR"
dpkg-deb --root-owner-group --build "$STAGE" "$OUTDIR/$DEB"

echo "==> Built: $OUTDIR/$DEB"
dpkg-deb -I "$OUTDIR/$DEB" | sed -n '1,20p'